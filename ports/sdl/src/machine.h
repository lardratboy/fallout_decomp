/*
 * machine.h -- the DOS/BIOS machine the game runs on.
 *
 * machine.c implements what src/fallout.c and src/gfx.c expect from DOS:
 * far memory, pseudo-registers, geninterrupt(), allocmem(), kbhit(),
 * sound()/delay().  Everything that depends on *how* the game is being run
 * (a real clock and keyboard, or a deterministic script) is delegated to a
 * backend.  The game only ever observes the machine through these calls, so
 * the replay backend exercises exactly the code the realtime one uses.
 */
#ifndef MACHINE_H
#define MACHINE_H

#include <stddef.h>
#include "dos.h"

#define VRAM        (shim_mem + 0xA0000)
#define VRAM_SIZE   64000

struct backend {
    unsigned long (*ticks)(void);       /* INT 1Ah/00h: every get_ticks() call  */
    int  (*kbhit)(void);                /* INT 21h/0Bh                          */
    int  (*getkey)(void);               /* INT 21h/07h: one byte, blocks        */
    void (*delay)(unsigned ms);
    void (*speaker)(unsigned divisor);  /* PIT channel 2 divisor, 0 = off       */
    void (*video_mode)(int mode);
    void (*palette)(const unsigned char *rgb, int first, int count);
    void (*con_out)(const char *s, size_t n);   /* INT 21h/09h, 02h         */
    int  (*boss_key)(const char *cmd);  /* system()                             */
    void (*quit)(int status);           /* program exit; never returns          */
};

extern const struct backend *be;

/* DS:DX for the BIOS/DOS calls that pass a buffer.  On a 64-bit host a
   pointer does not fit in _DX, so the wrappers in gfx_port.c put it here. */
extern void *shim_ptr;

/* start-up knobs (the replay backend sets these from the environment) */
extern int machine_alloc_fail;          /* ALLOC_FAIL=n, -1 = never fail        */
extern int machine_seed_forced;         /* srand() uses machine_seed instead    */
extern unsigned machine_seed;

void machine_init(const struct backend *b, int has_vga);

/* trace output (replay only; a no-op while trace_file is NULL) */
#include <stdio.h>
extern FILE *trace_file;
void trace(const char *fmt, ...);

/* tclib.c: DOS file handles used by INT 21h/3Fh, 40h */
int fo_dos_read(int fd, void *buf, unsigned n);
int fo_dos_write(int fd, const void *buf, unsigned n);

/* generated by tools/emu/mkport.py */
unsigned long h_score(void), h_total(void);
unsigned h_level(void), h_bonus(void);
int h_orient(void);
char *h_board(void), *h_piece(void);
int h_piece_row(void), h_piece_col(void);

int game_main(int argc, char *argv[]);

unsigned long crc32_buf(const unsigned char *p, size_t n);

#endif
