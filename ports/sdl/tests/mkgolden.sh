#!/bin/sh
# Regenerate golden.txt from traces of the ORIGINAL game, as written by
# tools/emu/run_all.sh (build/difftest/NAME.orig.trace).  Run it after adding
# or changing a test script; it needs no port build.
#
# usage: ports/sdl/tests/mkgolden.sh [TRACE_DIR]
# golden.txt: one line per script:  NAME SEED MAX_TICKS SHA256
# MAX_TICKS must be the value run_all.sh used (MAX_TICKS, default 40000).
ROOT=$(cd "$(dirname "$0")/../../.." && pwd)
DIR=${1:-$ROOT/build/difftest}
MAX=${MAX_TICKS:-40000}

sha256() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | cut -d' ' -f1
    else
        shasum -a 256 "$1" | cut -d' ' -f1
    fi
}

{
    echo "# SHA-256 of the original FALLOUT.EXE's trace for each tests/*.keys"
    echo "# script (tools/emu/run_original.py).  Generated by mkgolden.sh."
    echo "# NAME SEED MAX_TICKS SHA256"
    for s in "$ROOT"/tests/*.keys; do
        name=$(basename "$s" .keys)
        t=$DIR/$name.orig.trace
        if [ ! -f "$t" ]; then
            echo "mkgolden.sh: missing $t" >&2
            exit 1
        fi
        seed=$(sed -n 's/^srand //p' "$t" | head -1)
        echo "$name ${seed:-0} $MAX $(sha256 "$t")"
    done
} > "$ROOT/ports/sdl/tests/golden.txt"
