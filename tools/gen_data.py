#!/usr/bin/env python3
"""Generate the C data include files (sprites, palette, fonts, tables) from the
unpacked FALLOUT.EXE.  Every object is emitted at its original DGROUP offset so
that fallout.c, which #includes these files in order, reproduces the original
data segment layout byte for byte.

usage: gen_data.py FALLOUT_UNPACKED.EXE OUTDIR
"""
import os
import struct
import sys

DGROUP = 0x7EC0          # file-image offset of DGROUP (segment 0x07EC)


def load(path):
    d = open(path, 'rb').read()
    img = d[struct.unpack_from('<H', d, 8)[0] * 16:]
    return img[DGROUP:]


def rows(data, width, indent='    '):
    out = []
    for i in range(0, len(data), width):
        out.append(indent + ','.join('%3d' % b for b in data[i:i + width]) + ',')
    return '\n'.join(out)


def image_array(ds, name, off, count, w, h, comment):
    size = w * h
    s = ['/* %s: %d image(s), %dx%d, DS:%04X */' % (comment, count, w, h, off)]
    if count == 1:
        s.append('unsigned char %s[%d] = {' % (name, size))
        s.append(rows(ds[off:off + size], w))
    else:
        s.append('unsigned char %s[%d][%d] = {' % (name, count, size))
        for k in range(count):
            o = off + k * size
            s.append('  { /* %d @ DS:%04X */' % (k, o))
            s.append(rows(ds[o:o + size], w, '    '))
            s.append('  },')
    s.append('};')
    return '\n'.join(s) + '\n'


def ptr_table(ds, name, off, count, base_name, base_off, size, ctype='unsigned char *',
              per_line=4, dims=None):
    """Pointer table whose entries all point to base_name[k] (images of `size`)."""
    vals = [struct.unpack_from('<H', ds, off + 2 * i)[0] for i in range(count)]
    def ref(v):
        k, r = divmod(v - base_off, size)
        assert r == 0 and k >= 0, (name, hex(v))
        return '%s[%d]' % (base_name, k)
    s = ['/* DS:%04X */' % off]
    if dims:
        n_outer, n_inner = dims
        s.append('%s%s[%d][%d] = {' % (ctype, name, n_outer, n_inner))
        for i in range(n_outer):
            row = [ref(v) for v in vals[i * n_inner:(i + 1) * n_inner]]
            s.append('  { ' + ', '.join(row[:8]) + ',')
            s.append('    ' + ', '.join(row[8:]) + ' },')
    else:
        s.append('%s%s[%d] = {' % (ctype, name, count))
        refs = [ref(v) for v in vals]
        for i in range(0, count, per_line):
            s.append('    ' + ', '.join(refs[i:i + per_line]) + ',')
    s.append('};')
    return '\n'.join(s) + '\n'


HEADER = '/* Generated by tools/gen_data.py from FALLOUT.EXE -- do not edit. */\n\n'


def main(exe, outdir):
    ds = load(exe)
    os.makedirs(outdir, exist_ok=True)
    files = {}

    # --- title logo + palette -------------------------------------------
    # The logo is 81x15 but occupies 1216 bytes (one trailing pad byte).
    logo = image_array(ds, 'logo', 0x00A8, 1, 81, 15, 'FallOut logo')
    logo = logo.replace('unsigned char logo[1215] = {', 'unsigned char logo[1216] = {')
    logo = logo.replace('\n};', '\n      0,  /* pad byte present in the original */\n};')
    pal = ['/* VGA palette, 256 x RGB (6-bit), DS:0568 */',
           'unsigned char game_palette[768] = {']
    for i in range(256):
        r, g, b = ds[0x568 + 3 * i:0x568 + 3 * i + 3]
        pal.append('    %2d,%2d,%2d,  /* %3d */' % (r, g, b, i))
    pal.append('};')
    files['logo.inc'] = logo
    files['palette.inc'] = '\n'.join(pal) + '\n'

    # --- gem tiles, symbol sets, explosion --------------------------------
    t = image_array(ds, 'tiles', 0x0868, 100, 11, 11, 'gem tiles')
    t += '\n' + ptr_table(ds, 'tile_sets', 0x37AC, 160, 'tiles', 0x0868, 121, dims=(10, 16))
    t += '\n' + image_array(ds, 'explode_img', 0x38EC, 5, 11, 11, 'explosion frames')
    t += '\n' + ptr_table(ds, 'explode', 0x3B49, 5, 'explode_img', 0x38EC, 121, per_line=5)
    files['tiles.inc'] = t

    # --- title screen bricks ----------------------------------------------
    b = image_array(ds, 'brick_img', 0x3D1A, 4, 10, 10, 'title bricks')
    b += '\n' + ptr_table(ds, 'bricks', 0x3EAA, 4, 'brick_img', 0x3D1A, 100)
    b += '\n/* which bricks of a band are raised/shaded, DS:3EB2 */\n'
    b += 'char brick_pattern[200] = {\n' + rows(ds[0x3EB2:0x3EB2 + 200], 32) + '\n};\n'
    files['bricks.inc'] = b

    # --- title wave table (signed heights) ---------------------------------
    w = ds[0x46F0:0x46F0 + 2000]
    files['wave.inc'] = ('/* title "wave" heights, DS:46F0 */\nchar wave[2000] = {\n'
                         + rows(w, 25) + '\n};\n')

    # --- 8x8 font ----------------------------------------------------------
    f = image_array(ds, 'font8_img', 0x4EC3, 39, 8, 8,
                    '8x8 font: A-Z, 0-9, "-", space, "."')
    f += '\n' + ptr_table(ds, 'font8', 0x5883, 38, 'font8_img', 0x4EC3, 64)
    files['font8.inc'] = f

    # --- 6x6 font ----------------------------------------------------------
    f = image_array(ds, 'font6_img', 0x58D0, 42, 6, 6,
                    '6x6 font: A-Z, 0-9, ":", ".", ",", "#", "$", space')
    f += '\n' + ptr_table(ds, 'font6', 0x5EB8, 41, 'font6_img', 0x58D0, 36)
    files['font6.inc'] = f

    # --- bomb animations -----------------------------------------------------
    bm = image_array(ds, 'bomb1_img', 0x5F0A, 18, 11, 11, 'bomb (kind 1) animation')
    bm += '\n' + ptr_table(ds, 'bomb1', 0x678C, 27, 'bomb1_img', 0x5F0A, 121)
    bm += '\n' + image_array(ds, 'bomb2_img', 0x67C2, 18, 11, 11, 'bomb (kind 0) animation')
    bm += '\n' + ptr_table(ds, 'bomb2', 0x7044, 25, 'bomb2_img', 0x67C2, 121)
    files['bomb.inc'] = bm

    for name, text in files.items():
        with open(os.path.join(outdir, name), 'w') as fp:
            fp.write(HEADER + text)
        print('wrote', name)


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
