#!/usr/bin/env python3
"""Generate a random (but reproducible) key script for the differential test.

usage: gen_script.py SEED NKEYS > script.keys
"""
import random
import sys

GAME = (['4', '6', '2', '5', '8', 'SPACE', 'ENTER', 'TAB', 'i', 'j', 'k', 'l',
         'I', 'J', 'K', 'L', 'UP', 'LEFT', 'RIGHT', 'DOWN', 'PAD5'] * 6 +
        ['b', 'B', '+', 's', 'S', 'v', 'V', 'p', 'P'] +
        ['1', '2', '3', '4', '5', '6', '7'] * 2 + ['D', 'd', '9', 'BS', 'x', '-'])
RARE = ['A', 'a', 'Q', 'q', 'F10', 'F1', 'ESC']

def main():
    seed, n = int(sys.argv[1]), int(sys.argv[2])
    rng = random.Random(seed)
    tick = 40
    print('# generated by gen_script.py %d %d' % (seed, n))
    print('%d %s' % (tick, rng.choice('1234567')))
    for _ in range(n):
        tick += rng.choice([1, 2, 3, 5, 8, 13, 20, 40, 80])
        k = rng.choice(RARE) if rng.random() < 0.01 else rng.choice(GAME)
        print('%d %s' % (tick, k))

if __name__ == '__main__':
    main()
