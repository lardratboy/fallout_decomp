#!/usr/bin/env python3
"""Turn src/fallout.c into the source that native builds compile (the test
harness and ports/sdl).  src/ itself stays the faithful DOS version.

1. mkbss.py: the _BSS globals go into one packed struct, in original order,
   so the original's reads past array ends hit the same neighbours.
2. 16-bit arithmetic: Turbo C's int is 16 bits.  Where a value can actually
   leave 16 bits, the expression is patched to wrap like the original.  Each
   patch must match exactly once, so a change to src/ cannot silently skip it.
   (A blanket int -> int16_t rewrite would be wrong: C still computes in int,
   and int16/uint16 comparisons would become signed where DOS compared
   unsigned.)
3. Layout: struct hiscore gets its DOS layout (14 bytes, packed), so the
   table is the 140 bytes of FALLOUT.HIS and the file is read and written
   as is, scramble included.  Always applied: host long/int sizes would
   otherwise change the file format.
4. Accessors, so platform code reads game variables without redeclaring them.

Deliberately NOT reproduced (documented, not reachable in normal play):
  * strip_pos (int) overflows after ~5.5 hours on the About screen, after
    which the original indexes tile_sets out of bounds;
  * level / multiplier / bombs overflow (needs ~32k levels or bombs);
  * the 32-bit wrap of score / total (> 4.29 billion).

usage: mkport.py [--no-int16] fallout.c OUT_DIR
       -> OUT_DIR/fallout_port.c, OUT_DIR/bss_layout.h
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mkbss  # noqa: E402

# (old, new, why)
INT16_PATCHES = [
    ('unsigned bonus           = 0;',
     'unsigned short bonus     = 0;',
     'bonus is 16 bits: the end-of-game tally adds 1000 per level, so a game '
     'ending at level ~65+ (7+ symbols) wraps it on DOS'),
    ('score += n * multiplier / 2;',
     'score += (unsigned short)(n * multiplier) / 2;',
     'the product is computed in 16 bits before the division'),
    ('score += level * 100;',
     'score += (unsigned short)(level * 100);',
     'level * 100 is computed in 16 bits (wraps from level 656)'),
]

# (old, new, why); applied with or without --no-int16
LAYOUT_PATCHES = [
    ('struct hiscore {                    /* 14 bytes; table is sorted ascending   */\n'
     '    char name[8];\n'
     '    unsigned long score;\n'
     '    int  slot;                      /* set to the index at start-up, unused  */\n'
     '};',
     '#pragma pack(push, 1)\n'
     'struct hiscore {                    /* 14 bytes; table is sorted ascending   */\n'
     '    char name[8];\n'
     '    unsigned int score;\n'
     '    short slot;                     /* set to the index at start-up, unused  */\n'
     '};\n'
     '#pragma pack(pop)',
     'the DOS layout: 32-bit score, 16-bit slot, no padding'),
    ('sprintf(buf, "%05lu", hiscore[9 - i].score);',
     'sprintf(buf, "%05lu", (unsigned long)hiscore[9 - i].score);',
     'score is no longer an unsigned long'),
]

ACCESSORS = '''
/* FALLOUT.HIS is this table, byte for byte */
typedef char h_hiscore_is_140_bytes[sizeof hiscore == 140 ? 1 : -1];

/* accessors for platform code (generated by tools/emu/mkport.py) */
unsigned long h_score(void) { return score; }
unsigned long h_total(void) { return total; }
unsigned h_level(void) { return level; }
unsigned h_bonus(void) { return bonus; }
int h_orient(void) { return orient; }
'''


def apply(text, patches):
    for old, new, why in patches:
        n = text.count(old)
        if n != 1:
            sys.exit('mkport.py: patch for "%s" matched %d times (want 1)'
                     % (old.split('\n')[0], n))
        text = text.replace(old, new + '  /* mkport: ' + why + ' */')
    return text


def main(argv):
    int16 = True
    if argv and argv[0] == '--no-int16':
        int16 = False
        argv = argv[1:]
    if len(argv) != 2:
        sys.exit(__doc__)
    src, outdir = argv
    mkbss.main(src, outdir)
    bss_c = os.path.join(outdir, 'fallout_bss.c')
    text = open(bss_c).read()
    os.remove(bss_c)
    text = apply(text, LAYOUT_PATCHES)
    if int16:
        text = apply(text, INT16_PATCHES)
    text += ACCESSORS
    open(os.path.join(outdir, 'fallout_port.c'), 'w').write(text)


if __name__ == '__main__':
    main(sys.argv[1:])
