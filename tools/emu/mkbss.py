#!/usr/bin/env python3
"""For the native test build only: rewrite fallout.c so that its _BSS globals
live in one packed struct, in their original order.

The original game reads past the ends of some arrays (e.g. board[17][col] when
rotating a piece on the bottom row reads shell_cmd[4]).  To reproduce that
behaviour natively the variables must be adjacent in the same order, which a
host compiler does not guarantee for separate globals.

usage: mkbss.py fallout.c OUT_DIR   -> OUT_DIR/fallout_bss.c, OUT_DIR/bss_layout.h
"""
import os
import re
import sys

START = 'uninitialised data (_BSS)'
END = '/* ======'


def main(src, outdir):
    lines = open(src).read().split('\n')
    i0 = next(i for i, l in enumerate(lines) if START in l) + 1
    i1 = next(i for i in range(i0 + 1, len(lines)) if lines[i].startswith(END))
    decls, names = [], []
    for l in lines[i0:i1]:
        code = re.sub(r'/\*.*?\*/', '', l).strip()
        if not code:
            continue
        m = re.match(r'^(.*?)(\w+)\s*((?:\[\d+\])*)\s*;$', code)
        assert m, l
        decls.append(code)
        names.append(m.group(2))
    hdr = ['/* generated by tools/emu/mkbss.py */',
           '#pragma pack(push, 1)', 'struct bss_layout {']
    hdr += ['    %s' % d for d in decls]
    hdr += ['};', '#pragma pack(pop)', 'extern struct bss_layout bss;']
    hdr += ['#define %s (bss.%s)' % (n, n) for n in names]
    open(os.path.join(outdir, 'bss_layout.h'), 'w').write('\n'.join(hdr) + '\n')
    out = lines[:i0] + ['#include "bss_layout.h"', 'struct bss_layout bss;'] + lines[i1:]
    out += ['/* accessors for the harness */',
            'char *h_board(void) { return (char *)board; }',
            'char *h_piece(void) { return piece; }',
            'int h_piece_row(void) { return piece_row; }',
            'int h_piece_col(void) { return piece_col; }']
    open(os.path.join(outdir, 'fallout_bss.c'), 'w').write('\n'.join(out))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
